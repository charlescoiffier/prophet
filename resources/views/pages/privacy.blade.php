<x-text-page title="Données personnelles"
             lead="Quelles données nous gardons, pourquoi, et combien de temps.">
    <section>
        <h2>Si vous proposez une carte sans compte</h2>
        <p>Votre adresse e-mail sert uniquement à confirmer la proposition, à vous informer de sa publication ou de son refus, et à vous inviter à créer un compte. Elle n’est jamais publiée.</p>
        <p>Sans confirmation sous 7 jours, la proposition et l’adresse sont effacées. Si vous créez ensuite un compte avec cette adresse, vos cartes y sont rattachées et l’adresse n’est plus conservée sur la carte.</p>
    </section>

    <section>
        <h2>Si vous créez un compte</h2>
        <p>Nous gardons votre pseudo (public), votre adresse e-mail (jamais publiée) et votre mot de passe chiffré. L’historique public de chaque carte indique le pseudo des personnes qui l’ont proposée ou modérée.</p>
    </section>

    <section>
        <h2>Signalements</h2>
        <p>Le texte d’un signalement et l’adresse qui l’accompagne ne sont lus que par les modérateurs.</p>
    </section>

    <section>
        <h2>Ce que nous ne faisons pas</h2>
        <p>Pas de cookie publicitaire ni de mesure d’audience tierce. La vérification anti-robot fonctionne sans cookie. Seul un cookie de session est déposé pour vous garder connecté.</p>
        <p class="text-[13px] text-muted">Pour exercer vos droits (accès, rectification, effacement), écrivez à l’adresse indiquée dans les mentions légales.</p>
    </section>

    <x-slot:aside>
        <h2>En bref</h2>
        <p><b>Jamais publiée</b><br>Votre adresse e-mail ne sort pas des notifications.</p>
        <p><b>Effacée</b><br>Une proposition non confirmée disparaît, adresse comprise, sous 8 jours.</p>
        <p><b>Sans pistage</b><br>Ni cookie publicitaire, ni mesure d’audience tierce, ni captcha à cookies.</p>
    </x-slot:aside>
